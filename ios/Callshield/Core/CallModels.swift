import Foundation

enum Voice: String, CaseIterable, Equatable, Codable {
    case ai, human, unknown, analyzing

    var label: String {
        switch self {
        case .ai: return "Likely AI"
        case .human: return "Likely human"
        case .unknown: return "Unknown"
        case .analyzing: return "Analyzing voice"
        }
    }

    var explanation: String {
        switch self {
        case .ai: return "The voice may be generated by AI. This does not mean the caller is a scammer."
        case .human: return "The voice appears human. This does not verify the caller or mean the call is safe."
        case .unknown: return "There is not enough information to classify the voice."
        case .analyzing: return "Checking the simulated voice…"
        }
    }
}

enum AvatarColor: String, Codable { case rose, slate, blue, mint }

struct Person: Equatable, Identifiable, Codable {
    let name: String
    let number: String
    let initials: String
    let color: AvatarColor
    let voice: Voice
    var id: String { number }
}

struct CallEntry: Equatable, Identifiable {
    let id: String
    let person: Person
    let when: String
    let missed: Bool
    let duration: Int
    let voice: Voice
    var scamRisk: Int? = nil
}

struct ActiveCall: Equatable, Identifiable {
    enum Stage { case ringing, connected }
    let id: UUID
    let person: Person
    var stage: Stage
    var voice: Voice
    var started: Date
    var scamRisk: Int? = nil
}

// Demo and production share the same primary navigation.
typealias AppTab = PhoneTab

enum CallFilter: String, CaseIterable { case all = "All", missed = "Missed" }

enum AppSheet: Identifiable {
    case demo
    case call(CallEntry)
    case contact(Person)

    var id: String {
        switch self {
        case .demo: return "demo"
        case .call(let entry): return "call-\(entry.id)"
        case .contact(let person): return "contact-\(person.id)"
        }
    }
}

