export function VoiceBadge({ voice, help = false }: { voice: Voice; help?: boolean }) {
  const [open, setOpen] = useState(false);
  const helpId = useId();
  const explanation = voice === 'ai' ? 'The voice may be generated by AI. This does not mean the caller is a scammer.' : voice === 'human' ? 'The voice appears human. This does not verify the caller or mean the call is safe.' : voice === 'analyzing' ? 'The demo is checking the simulated voice. Results appear after a short delay.' : 'There is not enough information to classify the voice.';
  const Icon = voice === 'ai' ? Bot : voice === 'human' ? UserRound : AudioLines;
  return <span className="voice-with-help" onKeyDown={event => { if (event.key === 'Escape') { event.preventDefault(); event.stopPropagation(); setOpen(false); } }}><span className={`voice-badge ${voice}`}><Icon size={12} />{labels[voice]}</span>{help && <><button className="result-help" aria-label={`About ${labels[voice]}`} aria-expanded={open} aria-controls={helpId} onClick={() => setOpen(!open)}><Info size={16} /></button>{open && <span id={helpId} className="result-tooltip" role="tooltip">{explanation}</span>}</>}</span>;
}

